function theme($path = null) {
    global $THEME;
    if ($path === null) return $THEME;
    $ref = $THEME;
    foreach (explode('.', $path) as $k) {        // удобно: theme('colors.accent')
        $ref = $ref[$k] ?? null;
        if ($ref === null) break;
    }
    return $ref;
}
